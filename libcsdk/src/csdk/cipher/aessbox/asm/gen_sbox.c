static int read_sbox(uint8_t *out) {
  // Try to read 256 values from stdin; support hex like 0x63 or 63
  char buf[256];
  int count = 0;
  while (count < 256) {
    int c = getchar();
    if (c == EOF) break;
    if ((unsigned char)c <= ' ') continue;
    // read token
    int i = 0; buf[i++] = (char)c;
    while (i < (int)sizeof(buf)-1) {
      int d = getchar();
      if (d == EOF || (unsigned char)d <= ' ') { buf[i] = 0; break; }
      buf[i++] = (char)d;
    }
    buf[i] = 0;
    char *end = NULL;
    long v = strtol(buf, &end, 0);
    if (end == buf) return -1;
    if (v < 0 || v > 255) return -1;
    out[count++] = (uint8_t)v;
  }
  return count == 256 ? 0 : -1;
}

static uint8_t gmul_by_2(uint8_t b) {
  uint8_t p = (uint8_t)(b << 1);
  if (b & 0x80) p ^= 0x1b;
  return p;
}
static uint8_t gmul_by_3(uint8_t b) {
  return (uint8_t)(gmul_by_2(b) ^ b);
}

int main(int argc, char **argv) {
  const char *te_out = argc > 1 ? argv[1] : "Te_words.inc";
  const char *td_out = argc > 2 ? argv[2] : "Td_words.inc";
  uint8_t sbox[256];
  memcpy(sbox, default_sbox, 256);
  // If stdin has data, try to parse it
  if (!feof(stdin)) {
    // Peek
    int c = fgetc(stdin);
    if (c != EOF) {
      ungetc(c, stdin);
      if (read_sbox(sbox) != 0) {
        fprintf(stderr, "gen_sbox: failed to parse 256-byte S-box from stdin; using default\n");
      }
    }
  }
  // Compute inverse
  uint8_t inv[256];
  for (int i = 0; i < 256; i++) inv[sbox[i]] = (uint8_t)i;
  // Full emitter follows

  // Emit Te.inc with full .LAES_Te section
  FILE *fte = fopen(te_out, "w");
  if (!fte) { perror("Te.inc"); return 1; }

  // Te header
  fprintf(fte, ".LAES_Te:\n");
  // Te0 pairs (256 entries), pair duplicated as in original layout
  for (int i = 0; i < 256; i++) {
    uint8_t s = sbox[i];
    uint32_t te0 = ((uint32_t)gmul_by_3(s) << 24) | ((uint32_t)s << 16) | ((uint32_t)s << 8) | (uint32_t)gmul_by_2(s);
    // Original layout uses 0xa56363c6 for s=0x63 which corresponds to [0xa5,0x63,0x63,0xc6]
    // Our construction above matches that ordering.
    fprintf(fte, ".long\t0x%08x,0x%08x\n", te0, te0);
  }

  // Emit S-box 4 times as in reference file: 8 bytes per line, no extra spaces
  for (int k = 0; k < 4; k++) {
    for (int i = 0; i < 256; i += 8) {
      fprintf(fte, ".byte\t");
      for (int j = 0; j < 8; j++) {
        fprintf(fte, "0x%02x%s", sbox[i + j], (j == 7 ? "" : ","));
      }
      fprintf(fte, "\n");
    }
  }

  // Rcon (10 entries, big-endian words)
  fprintf(fte, ".long\t0x00000001, 0x00000002, 0x00000004, 0x00000008\n");
  fprintf(fte, ".long\t0x00000010, 0x00000020, 0x00000040, 0x00000080\n");
  fprintf(fte, ".long\t0x0000001b, 0x00000036, 0x80808080, 0x80808080\n");
  fprintf(fte, ".long\t0xfefefefe, 0xfefefefe, 0x1b1b1b1b, 0x1b1b1b1b\n");

  fclose(fte);

  // Emit Td.inc with full .LAES_Td section
  FILE *ftd = fopen(td_out, "w");
  if (!ftd) { perror("Td.inc"); return 1; }
  fprintf(ftd, ".LAES_Td:\n");
  for (int i = 0; i < 256; i++) {
    uint8_t si = inv[i];
    // Td word: [0x0e*si, 0x09*si, 0x0d*si, 0x0b*si]
    // bytes placed as big-endian within the 32-bit value, matching original layout
    // We'll implement gf multiply by {09,0B,0D,0E} via repeated gmul_by_2 and XORs.
    uint8_t x2 = gmul_by_2(si);
    uint8_t x4 = gmul_by_2(x2);
    uint8_t x8 = gmul_by_2(x4);
    uint8_t x9 = (uint8_t)(x8 ^ si);
    uint8_t xb = (uint8_t)(x8 ^ x2 ^ si);
    uint8_t xd = (uint8_t)(x8 ^ x4 ^ si);
    uint8_t xe = (uint8_t)(x8 ^ x4 ^ x2);
    uint32_t td0 = ((uint32_t)xe << 24) | ((uint32_t)x9 << 16) | ((uint32_t)xd << 8) | (uint32_t)xb;
    fprintf(ftd, ".long\t0x%08x,0x%08x\n", td0, td0);
  }
  // Emit four inverse S-box blocks (8 bytes per line), each followed by constants
  for (int block = 0; block < 4; block++) {
    for (int i = 0; i < 256; i += 8) {
      fprintf(ftd, ".byte\t");
      for (int j = 0; j < 8; j++) {
        fprintf(ftd, "0x%02x%s", inv[i + j], (j == 7 ? "" : ","));
      }
      fprintf(ftd, "\n");
    }
    fprintf(ftd, ".long\t0x80808080, 0x80808080, 0xfefefefe, 0xfefefefe\n");
    fprintf(ftd, ".long\t0x1b1b1b1b, 0x1b1b1b1b, 0, 0\n");
  }
  fclose(ftd);

  return 0;
}

